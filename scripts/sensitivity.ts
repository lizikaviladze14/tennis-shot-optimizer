/**
 * Sensitivity analysis for the Detailed model.
 *
 *   npx vite-node scripts/sensitivity.ts
 *
 * Writes docs/sensitivity-results.md (fully generated) and creates
 * docs/sensitivity.md if it's missing (never overwrites it).
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  createSensitivityDraws,
  DEFAULT_SENSITIVITY_SETUP,
  runSensitivity,
  type ParameterGroup,
  type SensitivityResult,
} from '../src/analysis/sensitivity'
import {
  calculationStepsMarkdown,
  GROUP_TITLES,
  formatAim,
  formatSensitivityPercent,
  formatSetupLine,
  sensitivityRows,
  summaryRows,
  VERDICT_LEGEND,
} from '../src/utils/sensitivityFormat'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const RESULTS_PATH = resolve(ROOT, 'docs/sensitivity-results.md')
const GUIDE_PATH = resolve(ROOT, 'docs/sensitivity.md')
const COMMAND = 'npx vite-node scripts/sensitivity.ts'

const setup = DEFAULT_SENSITIVITY_SETUP
const setupLine = formatSetupLine(setup, 'default positions')

function table(header: string[], rows: string[][], align: ('l' | 'r')[]): string {
  const line = (cells: string[]) => `| ${cells.join(' | ')} |`
  const separator = align.map((side) => (side === 'l' ? ':--' : '--:'))
  return [line(header), line(separator), ...rows.map(line)].join('\n')
}

function groupTable(result: SensitivityResult, group: ParameterGroup): string {
  const bold = (text: string, isBase: boolean) => (isBase ? `**${text}**` : text)
  return table(
    ['Parameter', 'Value', 'Recommended aim', 'Rally win', 'Cost of keeping the base aim'],
    sensitivityRows(result, group).map((row) => [
      row.parameter ?? '',
      ...[row.value, row.aim, row.rallyWin, row.cost].map((cell) => bold(cell, row.isBase)),
    ]),
    ['l', 'l', 'l', 'r', 'r'],
  )
}

function summaryTable(result: SensitivityResult): string {
  return table(
    ['Parameter', 'Changes the advice?', 'Largest cost', 'Verdict'],
    summaryRows(result.parameters).map((row) => [row.parameter, row.changesAdvice, row.largestCost, row.verdictLabel]),
    ['l', 'l', 'r', 'l'],
  )
}

function resultsMarkdown(result: SensitivityResult, date: string): string {
  return `<!-- Generated by scripts/sensitivity.ts on ${date}. Do not edit by hand. -->

# Sensitivity results

_Generated by \`scripts/sensitivity.ts\` on ${date}. Do not edit by hand. Run \`${COMMAND}\` to update._

**Setup:** ${setupLine}

**Base recommendation:** ${formatAim(result.base)}, rally win ${formatSensitivityPercent(result.base.pRallyWin)}

## How it's calculated

${calculationStepsMarkdown()}

## Summary

${summaryTable(result)}

${VERDICT_LEGEND}

## ${GROUP_TITLES.model}

${groupTable(result, 'model')}

## ${GROUP_TITLES.player}

${groupTable(result, 'player')}

${VERDICT_LEGEND}

"Cost of keeping the base aim" = (best score under the new value − score of the base aim under the new value) × 100,
in points per 100 shots (pts) of the score the search maximizes (P(rally win) − λ × P(miss)). It is never negative.
"Changes the advice?" is "Yes" if the recommended zone changes and the cost is at least 1 pt;
"Aim shifts within zone" if the zone stays but the aim moves inside it and the cost is at least 1 pt;
"Similar alternative" if the zone changes but the cost is below 1 pt; otherwise "No".
`
}

const GUIDE = `# Sensitivity analysis

How much each illustrative parameter of the Detailed model changes the
recommendation. All parameters are illustrative; this shows which guesses the
advice depends on, not which values are right.

## Setup

One base setup, ${setupLine}.
The search finds the recommended aim for the base setup. Then each parameter is
set to a low and a high value, with everything else at base, and the search runs
again with the same draws. Model guesses are moved by a fixed step around the
model's constants; player inputs are multiplied by 0.8 and 1.2 (opponent
consistency is capped at 1).

## How to run

    ${COMMAND}

This rewrites [sensitivity-results.md](./sensitivity-results.md). This file is
never overwritten. The same analysis runs in the app under Model analytics →
Test assumptions, where the setup can be changed.

## Model in symbols

- Landing: aim + σ_depth·z₁ along the shot + σ_side·z₂ across it, with z₁, z₂ standard normal draws.
- Ball speed for an aim at depth d past the net: v·f(d), where f goes linearly from f_min at d_min to 1 at the deepest landing.
- After the bounce the ball moves at b·v·f(d) and stays playable for T seconds.
- Margin m = distance the opponent needs to run − distance they can run in the time available, at the easiest point along the ball's path after the bounce (opponent speed v_opp).
- P(reach) = 1 / (1 + e^(k·m)); P(return) = c · P(reach).
- Rally value after a return that lands d past the net: q(d), linear from q₀ at the net to q₁ at the baseline.
- Each draw that lands in contributes 1 − (1 − q)·P(return); a miss contributes 0. P(rally win) is the mean.
- Score = P(rally win) − λ·P(miss). The search picks the aim with the highest score between d_min and the baseline.
- Cost of keeping the base aim = 100 × (best score − score of the base aim), both under the changed value, in points per 100 shots (pts).

## Results

See [sensitivity-results.md](./sensitivity-results.md).

## What this means

`

function main() {
  const draws = createSensitivityDraws(setup)
  const started = Date.now()
  const result = runSensitivity(setup, draws, (done, total) => {
    process.stdout.write(`\rSearch ${done} of ${total}…`)
  })
  process.stdout.write(`\rDone: ${result.searchCount} searches in ${((Date.now() - started) / 1000).toFixed(1)} s\n`)

  const date = new Date().toISOString().slice(0, 10)
  mkdirSync(dirname(RESULTS_PATH), { recursive: true })
  writeFileSync(RESULTS_PATH, resultsMarkdown(result, date))
  console.log(`Wrote ${RESULTS_PATH}`)

  if (existsSync(GUIDE_PATH)) {
    console.log(`Kept ${GUIDE_PATH} (exists, never overwritten)`)
  } else {
    writeFileSync(GUIDE_PATH, GUIDE)
    console.log(`Created ${GUIDE_PATH}`)
  }

  console.log(`\n${summaryTable(result)}\n\n${VERDICT_LEGEND}`)
}

main()
